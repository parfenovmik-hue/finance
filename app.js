/* ---------------- Форма операции ---------------- */

// kind: 'regular' — обычные счета, 'savings' — копилки, 'all' — все
const accKind = (a, kind) => kind === 'all' || !!a.savings === (kind === 'savings');
function firstAccount(exclude, kind = 'regular') {
  return live('accounts').filter((a) => !a.archived && a.id !== exclude && accKind(a, kind)).sort(byAcc)[0]?.id || '';
}
function usable(id, kind = 'all') { const a = byId('accounts', id); return a && !a.deleted && !a.archived && accKind(a, kind) ? id : ''; }

function openTxSheet(opts = {}) {
  const s = state.settings;
  const editing = opts.id ? byId('txs', opts.id) : null;
  const f = editing
    ? { ...editing, amountStr: String(editing.amount), toAmountStr: editing.toAmount ? String(editing.toAmount) : '', debtAmountStr: editing.debtAmount ? String(editing.debtAmount) : '', savDir: 'in', savAccount: '', savePartStr: '' }
    : { id: uid('t'), type: opts.type || 'expense', date: ymd(), account: opts.account || '', category: opts.category || '', toAccount: opts.toAccount || '', debt: opts.debt || '', debtAction: opts.debtAction || 'pay', amountStr: opts.amount ? String(opts.amount) : '', toAmountStr: '', debtAmountStr: '', note: '', savDir: opts.savDir || 'in', savAccount: '', savePartStr: '' };
  // Проценты в платеже по кредиту: считаются сами, пока их не поправили вручную
  f.interestStr = editing?.interest ? String(editing.interest) : '';
  f.interestAuto = !editing?.interest;

  // Перевод между обычным счётом и копилкой показываем во вкладке «Копилка»
  if (editing && editing.type === 'transfer' && isSav(editing.account) !== isSav(editing.toAccount)) {
    f.type = 'savings';
    if (isSav(editing.toAccount)) { f.savDir = 'in'; f.savAccount = editing.toAccount; }
    else { f.savDir = 'out'; f.savAccount = editing.account; f.account = editing.toAccount; }
  }

  const applyDefaults = () => {
    if (editing) return;
    if (['expense', 'income', 'savings'].includes(f.type) && !usable(f.account, 'regular')) f.account = usable(s.last[f.type], 'regular') || firstAccount();
    if (f.type === 'transfer') {
      if (!usable(f.account) || f.account === f.toAccount) f.account = (s.last.transfer !== f.toAccount && usable(s.last.transfer)) || firstAccount(f.toAccount);
      if (!f.toAccount || f.toAccount === f.account) f.toAccount = (s.last.transferTo !== f.account && usable(s.last.transferTo)) || firstAccount(f.account, 'all');
    }
    if (f.type === 'savings' && !usable(f.savAccount, 'savings')) f.savAccount = usable(s.last.savAccount, 'savings') || firstAccount('', 'savings');
    if (f.type === 'debt' && f.account === '' && s.last.debt !== '') f.account = usable(s.last.debt, 'regular') || firstAccount();
    if (f.type === 'debt' && !f.debt) f.debt = live('debts').find((d) => debtStats()[d.id].rest > 0.004)?.id || live('debts')[0]?.id || '';
  };
  applyDefaults();

  const accChips = (key, value, { exclude, allowNone, kind = 'all' } = {}) => {
    const accs = live('accounts').filter((a) => (!a.archived || a.id === value) && a.id !== exclude && accKind(a, kind)).sort(byAcc);
    const bal = balances();
    return `<div class="chips scroll" data-keep="${key}">
      ${allowNone ? `<button class="chip ${!value ? 'on' : ''}" data-act="f-set" data-k="${key}" data-v="">Без счёта</button>` : ''}
      ${accs.map((a) => `<button class="chip ${value === a.id ? 'on' : ''}" data-act="f-set" data-k="${key}" data-v="${a.id}">${esc(a.name)}<small class="num ${maskCls(a.id)}">${fmt(bal[a.id], a.currency)}</small></button>`).join('')}
    </div>`;
  };

  // Откуда и куда идут деньги при переводе / операции с копилкой
  const ends = () => (f.type === 'savings' ? (f.savDir === 'in' ? [f.account, f.savAccount] : [f.savAccount, f.account]) : [f.account, f.toAccount]);
  const isXfer = () => f.type === 'transfer' || f.type === 'savings';

  const amountCur = () => {
    if (f.type === 'debt' && !f.account) return byId('debts', f.debt)?.currency || 'RUB';
    return accCur(isXfer() ? ends()[0] : f.account);
  };

  const rateHint = () => {
    if (!isXfer()) return '';
    const [from, to] = ends();
    const c1 = accCur(from), c2 = accCur(to);
    if (c1 === c2) return '';
    const a = parseNum(f.amountStr), b = parseNum(f.toAmountStr);
    if (!(a > 0 && b > 0)) return 'Введи обе суммы — курс посчитается сам';
    const r = c1 === 'RUB' ? a / b : b / a;
    return `Курс обмена: 1 USDT = ${fmtNum(r, 'USDT')} ₽`;
  };

  const toAmountBlock = () => {
    const [from, to] = ends();
    if (!from || !to || accCur(from) === accCur(to)) return '';
    return `<div class="field-label">Зачислено</div>
      <div class="amount-box" style="padding:6px 0"><input id="f-to-amount" inputmode="decimal" autocomplete="off" placeholder="0" value="${esc(f.toAmountStr)}" style="font-size:32px"><span class="cur">${CUR[accCur(to)].sym}</span></div>
      <div class="hint" id="rate-hint" style="text-align:center">${rateHint()}</div>`;
  };

  const savingsList = () => live('accounts').filter((a) => a.savings && !a.archived).sort(byAcc);

  // Платёж по кредиту с процентами (в одной валюте со счётом)
  const loanPay = () => {
    const d = byId('debts', f.debt);
    return f.type === 'debt' && d?.kind === 'loan' && f.debtAction === 'pay' && (!f.account || accCur(f.account) === d.currency) ? d : null;
  };
  const syncInterest = () => {
    const d = loanPay();
    if (!d || !f.interestAuto) return;
    const amount = parseNum(f.amountStr);
    const i = loanInterest(d, f.date || ymd(), editing?.id);
    f.interestStr = String(amount > 0 ? Math.min(i, amount) : i);
  };
  const loanHint = () => {
    const d = loanPay();
    if (!d) return '';
    const amount = parseNum(f.amountStr), interest = parseNum(f.interestStr);
    const st = loanStateAt(d, f.date || ymd(), editing?.id);
    const principal = Math.max(0, round2(amount - interest));
    const days = Math.round((parseYmd(f.date || ymd()) - parseYmd(st.last)) / 864e5);
    return `Проценты с ${shortDate(st.last)} (${days} ${plural(days, ['день', 'дня', 'дней'])})${st.unpaid ? ` + недоплата ${fmt(st.unpaid, d.currency)}` : ''}, ставка ${fmtRate(d.rate)}%. В счёт долга: ${fmt(principal, d.currency)} · остаток станет ${fmt(Math.max(0, st.rest - principal), d.currency)}`;
  };

  const body = () => {
    syncInterest();
    const cur = amountCur();
    let dyn = '';
    if (f.type === 'expense' || f.type === 'income') {
      const cats = live('categories').filter((c) => c.kind === f.type).sort(byOrder);
      const savePart = f.type === 'income' && !editing && savingsList().length
        ? `<div class="field-label"><span>Сразу отложить в копилку</span></div>
          <div class="save-part">
            <input class="input num" id="f-save-part" inputmode="decimal" autocomplete="off" placeholder="0" value="${esc(f.savePartStr)}">
            ${[10, 20, 30].map((p) => `<button class="chip" data-act="f-part" data-v="${p}">${p}%</button>`).join('')}
          </div>` : '';
      dyn = `<div class="field-label">Счёт</div>${accChips('account', f.account, { kind: 'regular' })}
        ${savePart}
        <div class="field-label"><span>Категория</span></div>
        <div class="cat-grid">${cats.map((c) => `<button class="cat ${f.category === c.id ? 'on' : ''}" data-act="f-set" data-k="category" data-v="${c.id}"><span class="em">${catIcon(c)}</span>${esc(c.name)}</button>`).join('')}
          <button class="cat" data-act="cat-new-inline"><span class="em" style="color:var(--accent)"><svg viewBox="0 0 24 24"><path d="M12 5v14M5 12h14"/></svg></span>Новая</button></div>`;
    } else if (f.type === 'savings') {
      const savs = savingsList();
      if (!savs.length) {
        dyn = `<div class="card" style="margin-top:14px"><div class="empty">Копилки пока нет.<button class="btn small" data-act="sav-new">Создать копилку</button></div></div>`;
      } else {
        const sv = byId('accounts', f.savAccount);
        dyn = `<div class="field-label">Действие</div>
          <div class="seg">
            <button class="${f.savDir === 'in' ? 'on' : ''}" data-act="f-set" data-k="savDir" data-v="in">Положить</button>
            <button class="${f.savDir === 'out' ? 'on' : ''}" data-act="f-set" data-k="savDir" data-v="out">Забрать</button>
          </div>
          <div class="field-label">${f.savDir === 'in' ? 'С какого счёта' : 'На какой счёт'}</div>${accChips('account', f.account, { kind: 'regular' })}
          ${savs.length > 1 ? `<div class="field-label">Копилка</div>${accChips('savAccount', f.savAccount, { kind: 'savings' })}`
            : sv ? `<div class="hint">В копилке «${esc(sv.name)}»: <span class="num ${maskCls(sv.id)}">${fmt(balances()[sv.id], sv.currency)}</span></div>` : ''}
          ${toAmountBlock()}`;
      }
    } else if (f.type === 'transfer') {
      dyn = `<div class="field-label">Откуда</div>${accChips('account', f.account)}
        <div class="field-label">Куда</div>${accChips('toAccount', f.toAccount, { exclude: f.account })}
        ${toAmountBlock()}`;
    } else {
      const debts = live('debts');
      if (!debts.length) {
        dyn = `<div class="card" style="margin-top:14px"><div class="empty">Сначала добавь долг — кредит, рассрочку или кому ты должен.<button class="btn small" data-act="debt-new">Добавить долг</button></div></div>`;
      } else {
        const d = byId('debts', f.debt);
        const ds = debtStats();
        const needDebtAmt = d && f.account && accCur(f.account) !== d.currency;
        dyn = `<div class="field-label">Долг</div>
          <div class="chips scroll" data-keep="debt">${debts.map((x) => `<button class="chip ${f.debt === x.id ? 'on' : ''}" data-act="f-set" data-k="debt" data-v="${x.id}">${esc(x.name)}<small class="num">${fmt(Math.max(0, ds[x.id].rest), x.currency)}</small></button>`).join('')}</div>
          <div class="field-label">Действие</div>
          <div class="seg">
            <button class="${f.debtAction === 'pay' ? 'on' : ''}" data-act="f-set" data-k="debtAction" data-v="pay">${debtActionLabel(d, 'pay')}</button>
            <button class="${f.debtAction === 'add' ? 'on' : ''}" data-act="f-set" data-k="debtAction" data-v="add">${debtActionLabel(d, 'add')}</button>
          </div>
          <div class="field-label">${debtMoneyOut({ debt: f.debt, debtAction: f.debtAction }) ? 'С какого счёта' : 'На какой счёт'}</div>
          ${accChips('account', f.account, { allowNone: true, kind: 'regular' })}
          ${needDebtAmt ? `<div class="field-label">Сумма в валюте долга (${d.currency})</div><input class="input num" id="f-debt-amount" inputmode="decimal" autocomplete="off" placeholder="0" value="${esc(f.debtAmountStr)}">` : ''}
          ${loanPay() ? `<div class="field-label"><span>Из них проценты</span><span>можно поправить по банку</span></div>
            <input class="input num" id="f-interest" inputmode="decimal" autocomplete="off" placeholder="0" value="${esc(f.interestStr)}">
            <div class="hint" id="loan-hint">${loanHint()}</div>` : ''}`;
      }
    }
    const typeCls = f.type === 'expense' ? 'exp' : f.type === 'income' ? 'inc' : '';
    return `
      <div class="seg types">
        ${[['expense', 'Расход'], ['income', 'Доход'], ['savings', 'Копилка'], ['transfer', 'Между счетами'], ['debt', 'Долг']].map(([k, l]) => `<button class="${f.type === k ? 'on' : ''}" data-act="f-type" data-v="${k}">${l}</button>`).join('')}
      </div>
      <div class="amount-box ${typeCls}"><input id="f-amount" inputmode="decimal" autocomplete="off" placeholder="0" value="${esc(f.amountStr)}"><span class="cur">${CUR[cur].sym}</span></div>
      ${dyn}
      <div class="field-label">Дата и комментарий</div>
      <div class="two"><input class="input" type="date" id="f-date" value="${esc(f.date)}"><input class="input" id="f-note" placeholder="Комментарий" value="${esc(f.note)}"></div>
      <button class="btn" data-act="tx-save">${editing ? 'Сохранить' : 'Записать'}</button>
      ${editing ? `<button class="btn danger small" data-act="tx-delete">Удалить операцию</button>` : ''}`;
  };

  const saveTx = () => {
    const amount = round2(parseNum(f.amountStr));
    if (!(amount > 0)) return toast('Введи сумму');
    const t = {
      id: f.id, type: f.type, date: f.date || ymd(), account: f.account || '', amount,
      category: '', toAccount: '', toAmount: 0, debt: '', debtAction: '', debtAmount: 0, interest: 0,
      note: (f.note || '').trim(), createdAt: editing?.createdAt || Date.now(), deleted: false,
    };
    let partTx = null;
    if (f.type === 'expense' || f.type === 'income') {
      if (!t.account) return toast('Выбери счёт');
      if (!f.category) return toast('Выбери категорию');
      t.category = f.category;
      const part = f.type === 'income' && !editing ? round2(parseNum(f.savePartStr)) : 0;
      if (part > 0) {
        if (part > amount) return toast('В копилку больше, чем сам доход');
        const cur = accCur(t.account);
        const sav = [usable(s.last.savAccount, 'savings'), ...savingsList().map((a) => a.id)].find((id) => id && accCur(id) === cur);
        if (!sav) return toast(`Нет копилки в ${cur === 'RUB' ? 'рублях' : 'USDT'}`);
        partTx = {
          id: uid('t'), type: 'transfer', date: t.date, account: t.account, amount: part, category: '', toAccount: sav, toAmount: part,
          debt: '', debtAction: '', debtAmount: 0, note: 'С дохода', createdAt: Date.now() + 1, deleted: false,
        };
      }
    } else if (isXfer()) {
      const [from, to] = ends();
      if (!from || !to) return toast(f.type === 'savings' ? 'Выбери счёт и копилку' : 'Выбери оба счёта');
      if (from === to) return toast('Счета должны отличаться');
      t.type = 'transfer';
      t.account = from;
      t.toAccount = to;
      t.toAmount = accCur(from) === accCur(to) ? amount : round2(parseNum(f.toAmountStr));
      if (!(t.toAmount > 0)) return toast('Введи сумму зачисления');
    } else {
      const d = byId('debts', f.debt);
      if (!d) return toast('Выбери долг');
      t.debt = d.id;
      t.debtAction = f.debtAction;
      t.debtAmount = !t.account || accCur(t.account) === d.currency ? amount : round2(parseNum(f.debtAmountStr));
      if (!(t.debtAmount > 0)) return toast('Введи сумму в валюте долга');
      if (loanPay()) {
        t.interest = round2(parseNum(f.interestStr));
        if (t.interest < 0 || t.interest > amount) return toast('Проценты не могут быть больше платежа');
        t.debtAmount = round2(amount - t.interest);
      }
    }
    upsert('txs', t);
    if (partTx) upsert('txs', partTx);
    s.last[f.type] = f.account;
    if (f.type === 'transfer') s.last.transferTo = t.toAccount;
    if (f.type === 'savings') s.last.savAccount = f.savAccount;
    if (partTx) s.last.savAccount = partTx.toAccount;
    // Если в «Сегодня без трат» был отмечен этот день — снимаем отметку
    s.quietDays = (s.quietDays || []).filter((d) => d !== t.date);
    save();
    closeSheet();
    toast(editing ? 'Изменено' : partTx ? `Записано ✓ · ${fmt(partTx.amount, accCur(t.account))} в копилку` : 'Записано ✓');
  };

  const entry = openSheet({
    title: editing ? 'Операция' : 'Новая операция',
    right: '',
    refresh: (entry) => { entry.body.innerHTML = body(); entry.body.querySelectorAll('.amount-box input').forEach(fitAmount); },
    onInput: (e) => {
      const map = { 'f-amount': 'amountStr', 'f-to-amount': 'toAmountStr', 'f-debt-amount': 'debtAmountStr', 'f-save-part': 'savePartStr', 'f-interest': 'interestStr', 'f-date': 'date', 'f-note': 'note' };
      const k = map[e.target.id];
      if (!k) return;
      f[k] = e.target.value;
      if (e.target.closest('.amount-box')) fitAmount(e.target);
      const h = $('#rate-hint', entry.sh);
      if (h) h.textContent = rateHint();
      if (k === 'interestStr') f.interestAuto = false;
      const fi = $('#f-interest', entry.sh);
      if (fi && f.interestAuto && (k === 'amountStr' || k === 'date')) { syncInterest(); fi.value = f.interestStr; }
      const lh = $('#loan-hint', entry.sh);
      if (lh) lh.textContent = loanHint();
    },
    actions: {
      'f-type': (el) => { f.type = el.dataset.v; applyDefaults(); if (f.type !== 'expense' && f.type !== 'income') f.category = ''; refreshTopSheet(); },
      'f-set': (el) => {
        const k = el.dataset.k;
        f[k] = el.dataset.v;
        if (k === 'account' && f.type === 'transfer' && f.toAccount === f.account) f.toAccount = firstAccount(f.account, 'all');
        refreshTopSheet();
        if (k === 'category' && !editing && parseNum(f.amountStr) > 0 && f.account) saveTx();
      },
      'f-part': (el) => {
        const amount = parseNum(f.amountStr);
        if (!(amount > 0)) return toast('Сначала введи сумму дохода');
        f.savePartStr = String(round2((amount * Number(el.dataset.v)) / 100));
        refreshTopSheet();
      },
      'tx-save': saveTx,
      'tx-delete': () => { if (confirm('Удалить операцию?')) { softDelete('txs', f.id); closeSheet(); toast('Удалено'); } },
      'debt-new': () => openDebtSheet(null, (id) => { f.debt = id; applyDefaults(); }),
      'sav-new': () => openAccountSheet(null, { savings: true, name: 'Копилка' }, (id) => { f.savAccount = id; }),
      'cat-new-inline': () => openCategorySheet(null, f.type, (id) => { f.category = id; }),
    },
  });
  if (!editing) $('#f-amount', entry.sh)?.focus({ preventScroll: true });
}

